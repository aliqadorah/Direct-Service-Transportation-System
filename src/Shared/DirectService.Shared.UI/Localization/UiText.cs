    public static IReadOnlyDictionary<string, (string Ar, string En)> All => _all;

    /// <summary>
    /// Adds the text of the other UI libraries (platform, modules) once at start-up — the browser app's composition, <c>ClientComposition</c>
    /// (Stage 2 session 15, DT-369: a partial class cannot span libraries). Calling it again rebuilds the same set.
    /// </summary>
    public static void Use(params Dictionary<string, (string Ar, string En)>[] parts) => _all = Merge([Core(), Reports(), Settings(), .. parts]);

    private static Dictionary<string, (string Ar, string En)> Merge(params Dictionary<string, (string Ar, string En)>[] parts)
    {
        var all = new Dictionary<string, (string Ar, string En)>(StringComparer.Ordinal);
        foreach (var part in parts)
            foreach (var (k, v) in part)
                if (!all.TryAdd(k, v)) throw new InvalidOperationException("UI text key defined twice: " + k);
        return all;
    }

