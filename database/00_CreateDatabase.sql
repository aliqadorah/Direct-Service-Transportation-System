/* Direct Service Transportation — create the Master Database (deployment, run once by the DBA).
   Raw SQL by necessity: EF Core migrations cannot create a database with a collation in a script
   (EF applies the model collation only when it creates the database itself). Listed in BUILD_STATUS.md.

   After this, apply database/MasterDatabase_Idempotent.sql (generated by
   `dotnet ef migrations script --idempotent` on src/Hosts/DirectService.Database), then 90_ApplicationUser.sql.

   Collation approved at checkpoint 1 (Q-07): Arabic_100_CI_AI_SC_UTF8. */
IF DB_ID(N'DirectServiceMaster') IS NULL
BEGIN
    CREATE DATABASE [DirectServiceMaster] COLLATE Arabic_100_CI_AI_SC_UTF8;
END;
GO
IF CONVERT(nvarchar(128), DATABASEPROPERTYEX(N'DirectServiceMaster', 'Collation')) <> N'Arabic_100_CI_AI_SC_UTF8'
    THROW 50001, 'DirectServiceMaster exists with a different collation; expected Arabic_100_CI_AI_SC_UTF8.', 1;
GO
ALTER DATABASE [DirectServiceMaster] SET READ_COMMITTED_SNAPSHOT ON WITH ROLLBACK IMMEDIATE;
GO
